export const translations: Record<Language, Record<TKey, string>> = { en, hi, gu };

export type TVars = Record<string, string | number>;

export function getLang(): Language {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("ql_lang");
    if (saved === "en" || saved === "hi" || saved === "gu") return saved;
  }
  return "en";
}

export function setLang(lang: Language) {
  if (typeof window !== "undefined") {
    localStorage.setItem("ql_lang", lang);
    window.dispatchEvent(new Event("language-changed"));
  }
}

export const isTKey = (value: unknown): value is TKey => typeof value === "string" && value in en;

// API error code -> message key. VALIDATION errors carry a "v.*" key as their message (validators.ts).
const ERROR_KEYS: Record<string, TKey> = {
  UNAUTHORIZED: "err.unauthorized",
  NOT_FOUND: "err.notFound",
  PHONE_TAKEN: "err.phoneTaken",
  DATE_NOT_BOOKABLE: "book.errNotBookable",
  DATE_FULL: "book.errFull",
  ALREADY_BOOKED: "book.errAlready",
  NOT_CANCELLABLE: "err.notCancellable",
};

export function errorKey(err: unknown): TKey {
  const { code, message } = (err ?? {}) as { code?: string; message?: string };
  if (code === "VALIDATION" && isTKey(message)) return message;
  return (code && ERROR_KEYS[code]) || "err.internal";
}

export function translate(lang: Language, key: TKey, vars?: TVars): string {
  const text: string = translations[lang][key] ?? en[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text;
}

// Re-renders on language change. Starts in English so the server and the first client render match.
export function useT() {
  const [lang, setLangState] = useState<Language>("en");

  useEffect(() => {
    setLangState(getLang());
    const onChange = () => setLangState(getLang());
    window.addEventListener("language-changed", onChange);
    return () => window.removeEventListener("language-changed", onChange);
  }, []);

  const t = useCallback((key: TKey, vars?: TVars) => translate(lang, key, vars), [lang]);
  // A form-field message (zod gives "v.*" keys); anything else passes through
  const tm = useCallback((message?: string) => (isTKey(message) ? translate(lang, message) : message), [lang]);
  // Any thrown API/network error, in the active language
  const te = useCallback((err: unknown) => translate(lang, errorKey(err)), [lang]);
  return { t, tm, te, lang };
}
